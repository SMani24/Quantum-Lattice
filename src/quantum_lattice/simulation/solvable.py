"""Checkpointable star Metropolis sampling of the known solvable Z branch.

The edge spins start at +1 and remain in the orbit generated by star flips.
Their target probability is proportional to ``exp(sum_e b_e * s_e)``. This
module samples that known distribution; it does not search for a ground state.
"""

from __future__ import annotations

import copy
import hashlib
import math
from typing import Any

import numpy as np

from quantum_lattice.lattice import Lattice

try:
    from numba import njit
except ImportError:  # The reference backend needs only NumPy.
    njit = None


def _fields(lattice: Lattice, values: Any) -> np.ndarray:
    if np.iscomplexobj(values):
        raise ValueError("fields must contain one finite real value per edge")
    fields = np.array(values, dtype=np.float64, copy=True)
    if fields.shape != (lattice.n_edges,) or not np.all(np.isfinite(fields)):
        raise ValueError("fields must contain one finite real value per edge")
    fields.setflags(write=False)
    return fields


def _nonnegative_integer(value: Any, name: str) -> int:
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer)):
        raise ValueError(f"{name} must be an integer")
    value = int(value)
    if value < 0:
        raise ValueError(f"{name} must be nonnegative")
    return value


def _topology_fingerprint(lattice: Lattice) -> str:
    digest = hashlib.sha256()
    digest.update(str(lattice.n_vertices).encode("ascii"))
    digest.update(lattice.edge_vertex_indices.tobytes())
    digest.update(lattice.vertex_edge_indices.tobytes())
    digest.update(lattice.vertex_edge_mask.tobytes())
    return digest.hexdigest()


def _in_reference_orbit(lattice: Lattice, spins: np.ndarray) -> bool:
    """Check all graph-cycle constraints, including noncontractible loops."""
    pseudospins = np.zeros(lattice.n_vertices, dtype=np.int8)
    for root in range(lattice.n_vertices):
        if pseudospins[root]:
            continue
        pseudospins[root] = 1
        stack = [root]
        while stack:
            vertex = stack.pop()
            for edge in lattice.vertices[vertex].incident_edges:
                other = edge.vertex_ids[0] if edge.vertex_ids[1] == vertex else edge.vertex_ids[1]
                proposed = pseudospins[vertex] * spins[edge.id]
                if pseudospins[other] == 0:
                    pseudospins[other] = proposed
                    stack.append(other)
                elif pseudospins[other] != proposed:
                    return False
    return True


def _proposal_kernel(spins, fields, incidence, degrees, vertices, uniforms, lazy_probability):
    """Sequential dependent updates; shared by Python and compiled backends."""
    accepted = 0
    lazy = 0
    for sweep in range(vertices.shape[0]):
        for proposal in range(vertices.shape[1]):
            vertex = vertices[sweep, proposal]
            if uniforms[sweep, proposal, 0] < lazy_probability:
                lazy += 1
                continue
            local_field = 0.0
            for slot in range(degrees[vertex]):
                edge = incidence[vertex, slot]
                local_field += fields[edge] * spins[edge]
            uniform = uniforms[sweep, proposal, 1]
            if local_field <= 0.0 or uniform == 0.0 or math.log(uniform) < -2.0 * local_field:
                for slot in range(degrees[vertex]):
                    edge = incidence[vertex, slot]
                    spins[edge] = -spins[edge]
                accepted += 1
    return accepted, lazy


_compiled_kernel = njit(cache=True, nogil=True)(_proposal_kernel) if njit is not None else None


class StarMetropolisChain:
    """One chain for one known field instance and one fixed topological sector.

    A sweep is ``lattice.n_vertices`` uniformly chosen vertices, with
    replacement. Each proposal immediately updates the chain if accepted.
    A configurable self-loop probability prevents the all-accepted zero-field
    walk from becoming periodic. Set it to zero for the authors' proposal rule.

    Random values are generated by NumPy PCG64 once per sweep, independent of
    backend and ``advance`` chunk sizes. Checkpoints include the full RNG state.
    """

    def __init__(self, lattice: Lattice, fields: Any, seed: Any, *, backend: str = "auto", lazy_probability: float = 0.05):
        if backend not in {"auto", "python", "numba"}:
            raise ValueError("backend must be auto, python, or numba")
        if not np.isfinite(lazy_probability) or not 0.0 <= lazy_probability < 1.0:
            raise ValueError("lazy_probability must be finite and in [0, 1)")
        if backend == "numba" and _compiled_kernel is None:
            raise ImportError("The numba backend requires the optional numba dependency")
        self.lattice = lattice
        self.fields = _fields(lattice, fields)
        self.backend = "numba" if backend == "auto" and _compiled_kernel is not None else backend
        if self.backend == "auto":
            self.backend = "python"
        self.lazy_probability = float(lazy_probability)
        self.rng = np.random.Generator(np.random.PCG64(seed))
        self.spins = np.ones(lattice.n_edges, dtype=np.int8)
        self.attempted = 0
        self.accepted = 0
        self.lazy = 0

    def advance(self, sweeps: int) -> None:
        """Advance complete sweeps, including rejected and lazy proposals."""
        sweeps = _nonnegative_integer(sweeps, "sweeps")
        if sweeps == 0:
            return
        # Bound random-array memory even when a caller requests a very long run.
        # Sweep-wise generation preserves the stream across these internal chunks.
        remaining = sweeps
        kernel = _compiled_kernel if self.backend == "numba" else _proposal_kernel
        while remaining:
            count = min(remaining, 4096)
            vertices = np.empty((count, self.lattice.n_vertices), dtype=np.int64)
            uniforms = np.empty((count, self.lattice.n_vertices, 2), dtype=np.float64)
            for sweep in range(count):
                vertices[sweep] = self.rng.integers(self.lattice.n_vertices, size=self.lattice.n_vertices)
                uniforms[sweep] = self.rng.random((self.lattice.n_vertices, 2))
            accepted, lazy = kernel(self.spins, self.fields, self.lattice.vertex_edge_indices,
                                    self.lattice.vertex_degrees, vertices, uniforms, self.lazy_probability)
            self.attempted += count * self.lattice.n_vertices
            self.accepted += int(accepted)
            self.lazy += int(lazy)
            remaining -= count

    def snapshot(self) -> dict[str, Any]:
        """Return a JSON-compatible, independent checkpoint of this chain."""
        return {
            "version": 1,
            "topology_sha256": _topology_fingerprint(self.lattice),
            "fields": self.fields.tolist(),
            "lazy_probability": self.lazy_probability,
            "spins": self.spins.tolist(),
            "rng_state": copy.deepcopy(self.rng.bit_generator.state),
            "attempted": self.attempted,
            "accepted": self.accepted,
            "lazy": self.lazy,
        }

    @classmethod
    def from_snapshot(cls, lattice: Lattice, fields: Any, snapshot: dict[str, Any], *, backend: str = "auto", lazy_probability: float = 0.05) -> StarMetropolisChain:
        """Restore a compatible checkpoint, optionally changing the backend."""
        chain = cls(lattice, fields, 0, backend=backend, lazy_probability=lazy_probability)
        if snapshot.get("version") != 1 or snapshot.get("topology_sha256") != _topology_fingerprint(lattice):
            raise ValueError("checkpoint version or topology does not match")
        if not np.array_equal(snapshot.get("fields"), chain.fields):
            raise ValueError("checkpoint fields do not match")
        if snapshot.get("lazy_probability") != chain.lazy_probability:
            raise ValueError("checkpoint lazy proposal probability does not match")
        spins = np.asarray(snapshot.get("spins"))
        if spins.shape != (lattice.n_edges,) or not np.all((spins == 1) | (spins == -1)):
            raise ValueError("checkpoint spins must be +1 or -1 on every edge")
        if not _in_reference_orbit(lattice, spins):
            raise ValueError("checkpoint spins are outside the +1 reference star orbit")
        chain.spins[:] = spins
        chain.attempted = _nonnegative_integer(snapshot.get("attempted"), "attempted")
        chain.accepted = _nonnegative_integer(snapshot.get("accepted"), "accepted")
        chain.lazy = _nonnegative_integer(snapshot.get("lazy"), "lazy")
        if chain.attempted % lattice.n_vertices or chain.accepted + chain.lazy > chain.attempted:
            raise ValueError("checkpoint proposal counters are inconsistent")
        state = snapshot.get("rng_state")
        if not isinstance(state, dict) or state.get("bit_generator") != "PCG64":
            raise ValueError("checkpoint must contain a PCG64 RNG state")
        chain.rng.bit_generator.state = copy.deepcopy(state)
        return chain
